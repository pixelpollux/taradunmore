#!/usr/bin/env bash
# Regenerates the four build-src files that cannot re-export the real component
# because it imports next/link or next/image (neither runs in a standalone
# browser bundle: see NOTES.md). Each is a copy of its app/ui source with
# relative imports and a plain <a> / <img>. Run from anywhere:
#   bash .design-sync/make-shims.sh
# Re-run it after editing Card.tsx, BackLink.tsx, Avatar.tsx or CoverImage.tsx.
set -euo pipefail
cd "$(dirname "$0")/.."

header() {
	printf '// GENERATED by .design-sync/make-shims.sh from app/ui/%s.tsx. Do not edit here.\n// next/link and next/image are replaced by a plain <a> and <img> (see NOTES.md).\n' "$1"
}

fix() {
	# @/lib/cn and sibling ui imports -> relative paths the converter can follow;
	# ContentfulImage -> the shim next to these files.
	perl -pe '
		s#"\@/lib/cn"#"../../lib/cn"#g;
		s#"\@/lib/contentful-image"#"./contentful-image"#g;
		s#from "\./(\w+)"#from "../../app/ui/$1"#g;
	'
}

mk() {
	local name="$1"
	{
		header "$name"
		fix < "app/ui/$name.tsx"
	} > ".design-sync/build-src/$name.tsx"
}

mk Avatar
mk CoverImage
mk BackLink
mk Card

# next/link -> plain <a> in Card and BackLink.
for name in Card BackLink; do
	f=".design-sync/build-src/$name.tsx"
	perl -0pi -e '
		s#import Link from "next/link";\n##;
		s#(\n\n)(/\*\*|export|const)#\n\n// next/link stand-in: a plain anchor.\nconst Link = ({ href, ...props }: any) => <a href={href} {...props} />;\n$1$2#;
	' "$f"
done

# The default exports become named exports (an `export *` barrel drops defaults).
perl -pi -e 's/export default function (Avatar|CoverImage|BackLink)\b/export function $1/' \
	.design-sync/build-src/Avatar.tsx .design-sync/build-src/CoverImage.tsx .design-sync/build-src/BackLink.tsx

echo "build-src shims regenerated: Avatar CoverImage BackLink Card"
